  function createStudioTableTexture(T) {
    try {
      const c = document.createElement('canvas');
      c.width = 512;
      c.height = 512;
      const ctx = c.getContext('2d');
      if (!ctx) return null;
      const grad = ctx.createRadialGradient(256, 256, 30, 256, 256, 260);
      grad.addColorStop(0, '#5c3a21');
      grad.addColorStop(0.65, '#3d2412');
      grad.addColorStop(1, '#1a110b');
      ctx.fillStyle = grad;
      ctx.fillRect(0, 0, 512, 512);
      ctx.strokeStyle = 'rgba(255, 190, 130, 0.07)';
      ctx.lineWidth = 2;
      for (let y = 0; y < 512; y += 8) {
        ctx.beginPath();
        ctx.moveTo(0, y + Math.sin(y * 0.1) * 3);
        ctx.lineTo(512, y + Math.cos(y * 0.1) * 3);
        ctx.stroke();
      }
      const tex = new T.CanvasTexture(c);
      tex.needsUpdate = true;
      return tex;
    } catch {
      return null;
    }
  }

