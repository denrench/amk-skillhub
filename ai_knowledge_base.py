def extract_lesson_digest(blocks_json):
    """Builds a compact, spoiler-free digest of a lesson's theory, tools, and criteria from content_json."""
    if not blocks_json:
        return ""
    blocks = blocks_json
    if isinstance(blocks_json, str):
        try:
            blocks = json.loads(blocks_json)
        except Exception:
            return ""
    if not isinstance(blocks, list):
        return ""

    parts = []
    for b in blocks:
        if not isinstance(b, dict):
            continue
        btype = b.get("type", "")
        if btype == "hook" and b.get("content"):
            parts.append(f"Контекст урока: {str(b['content'])[:280]}")
        elif btype == "objectives" and isinstance(b.get("items"), list):
            items = "; ".join(str(x) for x in b["items"][:4])
            if items:
                parts.append(f"Цели: {items[:320]}")
        elif btype == "theory" and isinstance(b.get("chunks"), list):
            chunk_txts = []
            for ch in b["chunks"][:3]:
                if isinstance(ch, dict):
                    h = ch.get("heading") or ""
                    t = ch.get("text") or ""
                    chunk_txts.append(f"{h}: {t}"[:220])
            if chunk_txts:
                parts.append("Ключевая теория: " + " | ".join(chunk_txts))
        elif btype == "practical":
            desc = b.get("task_description") or b.get("prompt") or ""
            crits = b.get("guidelines") or b.get("criteria") or []
            if desc:
                parts.append(f"Практическое ТЗ: {str(desc)[:260]}")
            if isinstance(crits, list) and crits:
                parts.append("Критерии ТЗ: " + "; ".join(str(c) for c in crits[:5])[:300])
    return "\n".join(parts)[:1400]


def retrieve_domain_knowledge(specialty, query_text="", lesson_title="", max_standards=4):
    """
    Lightweight deterministic RAG retriever over AMK SkillHub's 5-specialty engineering corpus.
    Ranks standards and common mistakes by lexical overlap with lesson_title + query_text.
    """
    spec = (specialty or "it").strip().lower()
    profile = SPECIALTY_PROFILES.get(spec, SPECIALTY_PROFILES["it"])
    q_tokens = _tokenize(f"{lesson_title} {query_text}")

    def rank_items(items, limit):
        scored = []
        for idx, item in enumerate(items):
            overlap = len(q_tokens & _tokenize(item))
            scored.append((overlap, -idx, item))
        scored.sort(reverse=True)
        return [x[2] for x in scored[:limit]]

    top_standards = rank_items(profile["standards"], max_standards)
    top_mistakes = rank_items(profile["common_mistakes"], 2)
    analogies = profile.get("analogies", [])

    return {
        "specialty": spec,
        "title": profile["title"],
        "mentor_role": profile["mentor_role"],
        "standards": top_standards,
        "common_mistakes": top_mistakes,
        "analogies": analogies,
    }


